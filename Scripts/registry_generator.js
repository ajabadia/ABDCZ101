#!/usr/bin/env node
/**
 * ABDCZ101 — Generador y Validador del Registro de Parámetros (SSOT Contract-Driven)
 * =================================================================================
 * Lee el contrato canónico de parámetros en:
 *   ABDSharedAssets/contracts/casio_cz101_parameter_spec.json
 * y emite / valida los CUATRO artefactos que consumen el host C++, WASM y la WebUI:
 *
 *   1. schemas/parameter-registry.data.json      (Esquema declarativo serializado)
 *   2. Source/State/ParameterRegistry.gen.h      (Cabecera C++ de especificaciones)
 *   3. Source/State/ParameterRegistry.gen.cpp    (Tablas estáticas y lookups C++)
 *   4. WebUI/src/contracts/registry.gen.js       (Mapeos JS, constantes y normalización)
 *
 * USO:
 *   node Scripts/registry_generator.js          # Genera y escribe los artefactos
 *   node Scripts/registry_generator.js --check  # Modo de guardia: valida sin escribir.
 *                                               # Código 0 si está al día, 1 si hay drift.
 *   node Scripts/registry_generator.js --help   # Ayuda
 */

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const ROOT_DIR = path.resolve(__dirname, '..');
const SCHEMAS_DIR = path.join(ROOT_DIR, 'schemas');
const CPP_STATE_DIR = path.join(ROOT_DIR, 'Source', 'State');
const WEBUI_CONTRACTS_DIR = path.join(ROOT_DIR, 'WebUI', 'src', 'contracts');

const CONTRACT_PATH = path.resolve(ROOT_DIR, '..', 'ABDSharedAssets', 'contracts', 'casio_cz101_parameter_spec.json');
const FALLBACK_DATA_PATH = path.join(SCHEMAS_DIR, 'parameter-registry.data.json');

const args = process.argv.slice(2);
const isCheckMode = args.includes('--check');
const isHelpMode = args.includes('--help') || args.includes('-h');

if (isHelpMode) {
  console.log(`
Uso: node Scripts/registry_generator.js [opciones]

Opciones:
  --check    Comprueba si los artefactos en disco están sincronizados con el contrato.
             No escribe en disco. Termina con código 0 si coincide, 1 si difiere.
  --help, -h Muestra este mensaje de ayuda.
`);
  process.exit(0);
}

// ── 1. Cargar Contrato SSOT ──────────────────────────────────────────────
let rawSpec;
if (fs.existsSync(CONTRACT_PATH)) {
  rawSpec = JSON.parse(fs.readFileSync(CONTRACT_PATH, 'utf8'));
} else if (fs.existsSync(FALLBACK_DATA_PATH)) {
  console.warn(`[registry] Aviso: No se encontró ${CONTRACT_PATH}. Usando fallback local.`);
  rawSpec = JSON.parse(fs.readFileSync(FALLBACK_DATA_PATH, 'utf8'));
} else {
  console.error(`[registry] Error fatal: No se encuentra el contrato de parámetros en ${CONTRACT_PATH}`);
  process.exit(1);
}

const parameters = rawSpec.parameters.map((p) => {
  const normType = p.type === 'integer' ? 'int' : p.type === 'boolean' ? 'bool' : p.type;
  const item = {
    id: p.id,
    name: p.name,
    category: p.category || p.group || 'General',
    type: normType,
    min: p.min,
    max: p.max,
    default: p.default,
  };
  if (p.choices) item.choices = p.choices;
  if (p.step !== undefined) item.step = p.step;
  if (p.unit !== undefined && p.unit !== 'normalized' && p.unit !== 'linear') item.unit = p.unit;
  if (p.skew !== undefined) item.skew = p.skew;
  return item;
});

const registryData = {
  schemaVersion: 1,
  pluginId: 'CZ101Emulator',
  parameters: parameters,
};

function toCppFloat(val) {
  const s = val.toString();
  if (s.indexOf('.') === -1 && s.indexOf('e') === -1) {
    return s + '.0f';
  }
  return s + 'f';
}

// ── 2. Generar Contenidos en Memoria ─────────────────────────────────────
const dataJsonContent = JSON.stringify(registryData, null, 2) + '\n';

const cppHeaderContent = `// Auto-generated by scripts/registry_generator.js - DO NOT EDIT MANUALLY
#pragma once

#include <juce_core/juce_core.h>
#include <vector>
#include <string>

namespace CZ101 {
namespace ParameterRegistry {

enum class ParamType { Float, Int, Choice, Bool };

struct ParameterSpec {
    const char* id;
    const char* name;
    const char* category;
    ParamType type;
    float minValue;
    float maxValue;
    float defaultValue;
    float step;
    const char* unit;
    float skew; // Non-symmetric skew factor (1.0 = linear), mirrors juce::NormalisableRange
};

extern const std::vector<ParameterSpec>& getRegistry();
const ParameterSpec* findSpec(const juce::String& paramId);

} // namespace ParameterRegistry
} // namespace CZ101
`;

const cppSourceContent = `// Auto-generated by scripts/registry_generator.js - DO NOT EDIT MANUALLY
#include "ParameterRegistry.gen.h"

namespace CZ101 {
namespace ParameterRegistry {

static const std::vector<ParameterSpec> g_registry = {
${parameters.map((p) => {
  const typeEnum = p.type === 'float' ? 'ParamType::Float' : p.type === 'int' ? 'ParamType::Int' : p.type === 'choice' ? 'ParamType::Choice' : 'ParamType::Bool';
  const unit = p.unit ? `"${p.unit}"` : '""';
  const step = p.step || 0.0;
  const skew = p.skew || 1.0;
  return `    { "${p.id}", "${p.name}", "${p.category}", ${typeEnum}, ${toCppFloat(p.min)}, ${toCppFloat(p.max)}, ${toCppFloat(p.default)}, ${toCppFloat(step)}, ${unit}, ${toCppFloat(skew)} }`;
}).join(',\n')}
};

const std::vector<ParameterSpec>& getRegistry() {
    return g_registry;
}

const ParameterSpec* findSpec(const juce::String& paramId) {
    for (const auto& spec : g_registry) {
        if (paramId == spec.id) return &spec;
    }
    return nullptr;
}

} // namespace ParameterRegistry
} // namespace CZ101
`;

const jsRegistryContent = `// Auto-generated by scripts/registry_generator.js - DO NOT EDIT MANUALLY
export const PARAMETER_REGISTRY = ${JSON.stringify(registryData, null, 2)};

export const PARAM_MAP = new Map(
  PARAMETER_REGISTRY.parameters.map(p => [p.id, p])
);

/**
 * La regla de skew del proyecto, en UN solo sitio. Un parametro con skew lleva
 * el control en NORMALIZADO (es lo que escribe \`applyParameterToUI\` y lo que lee
 * el motor) y sin skew lo lleva en CRUDO. \`skew: 1.0\` es identidad: cuenta como
 * SIN skew, que es como lo trata \`juce::NormalisableRange\`.
 *
 * @param {{skew?: number}} spec
 * @returns {boolean}
 */
export const usesSkew = (spec) => Boolean(spec && spec.skew != null && spec.skew !== 1.0);

export function rawToNormalized(paramId, rawValue) {
  const spec = PARAM_MAP.get(paramId);
  if (!spec) return 0.0;
  const range = spec.max - spec.min;
  if (range === 0) return 0.0;
  const proportion = Math.min(1.0, Math.max(0.0, (rawValue - spec.min) / range));
  // Reproduce juce::NormalisableRange::convertTo0to1 for a non-symmetric skew.
  // With skew < 1 (e.g. 0.3 on the filter cutoffs) the lower end of the range
  // fills more of the normalized space, exactly like the native APVTS.
  if (usesSkew(spec)) {
    return Math.pow(proportion, spec.skew);
  }
  return proportion;
}

export function normalizedToRaw(paramId, normalizedValue) {
  const spec = PARAM_MAP.get(paramId);
  if (!spec) return 0.0;
  const clampedNorm = Math.min(1.0, Math.max(0.0, normalizedValue));
  let proportion = clampedNorm;
  // Reproduce juce::NormalisableRange::convertFrom0to1 for a non-symmetric skew
  // (inverse of rawToNormalized: norm -> pow(norm, 1/skew)).
  if (usesSkew(spec)) {
    proportion = Math.pow(clampedNorm, 1.0 / spec.skew);
  }
  const raw = spec.min + proportion * (spec.max - spec.min);
  if (spec.type === 'int' || spec.type === 'choice' || spec.type === 'bool') {
    return Math.round(raw);
  }
  return raw;
}
`;

// ── 3. Manifiesto de Artefactos ──────────────────────────────────────────
const ARTEFACTOS = [
  {
    clave: 'dataJson',
    rel: 'schemas/parameter-registry.data.json',
    abs: path.join(SCHEMAS_DIR, 'parameter-registry.data.json'),
    content: dataJsonContent,
    consumidores: 'Validación de esquema JSON y tests de contrato',
  },
  {
    clave: 'h',
    rel: 'Source/State/ParameterRegistry.gen.h',
    abs: path.join(CPP_STATE_DIR, 'ParameterRegistry.gen.h'),
    content: cppHeaderContent,
    consumidores: 'Source/State/ParameterRegistry.gen.cpp y APVTS',
  },
  {
    clave: 'cpp',
    rel: 'Source/State/ParameterRegistry.gen.cpp',
    abs: path.join(CPP_STATE_DIR, 'ParameterRegistry.gen.cpp'),
    content: cppSourceContent,
    consumidores: 'Enlace C++ de tablas estáticas del plugin',
  },
  {
    clave: 'js',
    rel: 'WebUI/src/contracts/registry.gen.js',
    abs: path.join(WEBUI_CONTRACTS_DIR, 'registry.gen.js'),
    content: jsRegistryContent,
    consumidores: 'WebUI (PARAM_MAP, rawToNormalized, normalizedToRaw)',
  },
];

// Normaliza saltos de línea CRLF/LF para comparación en disco
function normalizeLineEndings(str) {
  return str.replace(/\r\n/g, '\n').trim();
}

// ── 4. Ejecución: Modo --check o Escritura ────────────────────────────────
if (isCheckMode) {
  let hasDiff = false;
  console.log(`[registry] Verificando paridad de los ${ARTEFACTOS.length} artefactos contra ${path.basename(CONTRACT_PATH)}...`);

  for (const art of ARTEFACTOS) {
    if (!fs.existsSync(art.abs)) {
      console.error(`  ✖ [FALTA]: ${art.rel} no existe en disco.`);
      hasDiff = true;
      continue;
    }
    const diskContent = fs.readFileSync(art.abs, 'utf8');
    if (normalizeLineEndings(diskContent) !== normalizeLineEndings(art.content)) {
      console.error(`  ✖ [DESINCRONIZADO]: ${art.rel} difiere del contrato generado.`);
      hasDiff = true;
    } else {
      console.log(`  ✔ [OK]: ${art.rel}`);
    }
  }

  if (hasDiff) {
    console.error('\n[registry] ERROR: Se detectaron artefactos desactualizados o ausentes.');
    console.error('           Ejecuta "node Scripts/registry_generator.js" para regenerarlos.');
    process.exit(1);
  }

  console.log('\n[registry] CHECK OK: Todos los artefactos están perfectamente sincronizados.');
  process.exit(0);
}

// Modo Escritura
for (const art of ARTEFACTOS) {
  fs.mkdirSync(path.dirname(art.abs), { recursive: true });
  fs.writeFileSync(art.abs, art.content, 'utf8');
  console.log(`  ✔ Generado: ${art.rel}`);
}

console.log(`\n✅ Éxito: ${ARTEFACTOS.length} artefactos regenerados correctamente desde ${path.basename(CONTRACT_PATH)}.`);
